/**
 * Resolves any raw district input (Marathi/English, abbreviation, alias)
 * to its canonical Marathi district name.
 */
export function normalizeDistrict(input) {
  if (!input || typeof input !== 'string') return null;
  const clean = input.trim().toLowerCase();

  // 1. Direct alias match
  if (DISTRICT_ALIASES[clean]) {
    return DISTRICT_ALIASES[clean];
  }

  // 2. Check if clean contains any known alias as a substring
  for (const [alias, canonical] of Object.entries(DISTRICT_ALIASES)) {
    if (clean === alias || clean.includes(alias)) {
      return canonical;
    }
  }

  // 3. Fallback to exact key check
  const exactKey = Object.keys(MAHARASHTRA_DISTRICTS_TALUKAS).find(d => 
    d === input.trim() || input.trim().includes(d)
  );

  return exactKey || null;
}

/**
 * Returns the array of Talukas for a given District in Marathi.
 * If the district is not recognized or not yet selected, returns an empty array.
 */
export function getTalukasForDistrict(districtInput) {
  const canonical = normalizeDistrict(districtInput);
  if (!canonical || !MAHARASHTRA_DISTRICTS_TALUKAS[canonical]) {
    return [];
  }
  return [...MAHARASHTRA_DISTRICTS_TALUKAS[canonical]];
}

/**
 * Matches a voice-recognized or typed string against the Taluka list of the selected District.
 * Supports partial matching, case-insensitivity, and phonetic similarity.
 * Returns the exact Marathi Taluka name if a match is found, or null otherwise.
 */
export function matchTalukaInDistrict(spokenText, districtInput) {
  if (!spokenText || typeof spokenText !== 'string') return null;
  const talukas = getTalukasForDistrict(districtInput);
  if (talukas.length === 0) return null;

  const rawClean = spokenText.trim().toLowerCase();

  // 1. Exact Marathi match
  const exact = talukas.find(t => t.toLowerCase() === rawClean);
  if (exact) return exact;

  // 2. Substring match (e.g. user says "हवेली तालुका" or "मावळ मध्ये")
  const substringMatch = talukas.find(t => {
    const tClean = t.toLowerCase();
    return rawClean.includes(tClean) || tClean.includes(rawClean);
  });
  if (substringMatch) return substringMatch;

  // 3. Normalized Marathi speech match (remove filler words)
  const stripped = rawClean
    .replace(/(तालुका|गाव|मध्ये|येथे|माझा|माझे|आहे|राहतो|राहते|तहसील)/g, '')
    .trim();

  if (stripped) {
    const strippedMatch = talukas.find(t => {
      const tClean = t.toLowerCase();
      return stripped.includes(tClean) || tClean.includes(stripped);
    });
    if (strippedMatch) return strippedMatch;
  }

  return null;
}
